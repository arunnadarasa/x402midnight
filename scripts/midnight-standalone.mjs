#!/usr/bin/env node
// scripts/midnight-standalone.mjs
// Bring up / tear down the local Midnight Undeployed stack:
//   node (0.22.5) + indexer-standalone (4.0.2) + proof-server (8.0.3)
//
// Usage:
//   bun scripts/midnight-standalone.mjs up      # write compose + docker compose up -d
//   bun scripts/midnight-standalone.mjs down    # docker compose down -v
//   bun scripts/midnight-standalone.mjs status  # ping node RPC, indexer GraphQL, proof server
//
// The canonical compose file is written to .midnight/standalone.docker-compose.yml
// so it stays out of the app source tree. Env values mirror the official
// midnightntwrk/midnight-local-dev repo.

import { mkdirSync, writeFileSync, existsSync } from "node:fs";
import { spawnSync } from "node:child_process";
import { resolve } from "node:path";

const ROOT = resolve(process.cwd());
const DIR = resolve(ROOT, ".midnight");
const COMPOSE = resolve(DIR, "standalone.docker-compose.yml");

const NODE_IMG    = "midnightntwrk/midnight-node:0.22.5";
const INDEXER_IMG = "midnightntwrk/indexer-standalone:4.0.2";
const PROOF_IMG   = "midnightntwrk/proof-server:8.0.3";

const COMPOSE_YAML = `# Auto-generated by scripts/midnight-standalone.mjs — do not edit by hand.
# Pinned per lovable-midnight support matrix (Undeployed column).
name: midnight-standalone

services:
  proof-server:
    image: ${PROOF_IMG}
    container_name: midnight-proof
    command: ["midnight-proof-server", "-v"]
    ports: ["6300:6300"]
    restart: unless-stopped

  node:
    image: ${NODE_IMG}
    container_name: midnight-node
    environment:
      CFG_PRESET: "dev"
    ports:
      - "9944:9944"
      - "9933:9933"
    restart: unless-stopped

  indexer:
    image: ${INDEXER_IMG}
    container_name: midnight-indexer
    depends_on: [node]
    environment:
      APP__INFRA__NODE__URL: "ws://node:9944"
      APP__APPLICATION__NETWORK_ID: "undeployed"
      APP__INFRA__STORAGE__PASSWORD: "indexer"
      APP__INFRA__PUB_SUB__PASSWORD: "indexer"
      APP__INFRA__LEDGER_STATE_STORAGE__PASSWORD: "indexer"
      # 32-byte hex secret (required by indexer 4.0.2)
      APP__INFRA__SECRET: "303132333435363738393031323334353637383930313233343536373839303132"
      # Blockfrost placeholder is required to satisfy config parsing
      APP__INFRA__SPO_NODE__BLOCKFROST_ID: "placeholder"
    ports: ["8088:8088"]
    restart: unless-stopped
`;

function ensureCompose() {
  if (!existsSync(DIR)) mkdirSync(DIR, { recursive: true });
  writeFileSync(COMPOSE, COMPOSE_YAML);
  return COMPOSE;
}

function docker(args) {
  const r = spawnSync("docker", args, { stdio: "inherit" });
  if (r.status !== 0) process.exit(r.status ?? 1);
}

async function ping(label, fn) {
  try {
    const ok = await fn();
    console.log(`${ok ? "✔" : "✘"} ${label}`);
  } catch (e) {
    console.log(`✘ ${label} — ${e?.message ?? e}`);
  }
}

async function status() {
  await ping("node RPC (:9944)", async () => {
    const r = await fetch("http://localhost:9944", {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ id: 1, jsonrpc: "2.0", method: "system_health", params: [] }),
    });
    return r.ok;
  });
  await ping("indexer GraphQL (:8088)", async () => {
    // indexer-standalone:4.0.2 serves GraphQL on /api/v4/graphql; /api/v1 loops via 308.
    const r = await fetch("http://localhost:8088/api/v4/graphql", {
      method: "POST",
      headers: { "content-type": "application/json" },
      body: JSON.stringify({ query: "{ __typename }" }),
    });
    return r.ok;
  });
  await ping("proof server (:6300)", async () => {
    const r = await fetch("http://localhost:6300/health").catch(() => null);
    // Proof server may not expose /health; a TCP-level 404 is still "up".
    return !!r;
  });
}

const cmd = process.argv[2] ?? "up";

switch (cmd) {
  case "up": {
    const file = ensureCompose();
    console.log(`→ wrote ${file}`);
    docker(["compose", "-f", file, "up", "-d", "--force-recreate"]);
    console.log("→ containers started. Run: bun scripts/midnight-standalone.mjs status");
    break;
  }
  case "down": {
    const file = ensureCompose();
    docker(["compose", "-f", file, "down", "-v"]);
    break;
  }
  case "status": {
    await status();
    break;
  }
  case "logs": {
    const file = ensureCompose();
    docker(["compose", "-f", file, "logs", "-f", "--tail=100"]);
    break;
  }
  default:
    console.error(`unknown command: ${cmd}\nusage: bun scripts/midnight-standalone.mjs <up|down|status|logs>`);
    process.exit(2);
}
